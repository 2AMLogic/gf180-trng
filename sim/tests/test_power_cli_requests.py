#!/usr/bin/env python3
"""The request-builder contract shared by the four power tools (issue #840).

``power_switch``, ``power_retention``, ``power_switch_decay`` and
``liveness_sampler_power`` build their ``klt sim`` requests through one helper in
``sim/tools/_power_cli.py``. The committed ``request*.json`` under each testbench is
generated evidence guarded by ``emit --check``, so the shared builder has to reproduce each
tool's request *byte for byte* -- including the differences the tools must NOT share.

This file pins those differences: the supply parameter name, the ``analysis.args`` format,
which of ``remote`` / ``batch`` are present at all, ``options.timeout_s``, ``ngspice_init``,
the top-level key order, and the single-point ``--only`` probe. A shared builder that
unified any of them (one timeout for all four, a ``batch`` block everywhere, ``remote`` on
the sampler) would still emit valid JSON and would still pass a schema check -- it would
silently rewrite committed evidence. These assertions are what makes that a test failure.

No ngspice, no PDK, no ``klt``, no network: every assertion is on a dict built in-process.
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

SIM_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SIM_DIR / "tools"))

import liveness_sampler_power as lsp  # noqa: E402
import power_retention as pr  # noqa: E402
import power_switch as ps  # noqa: E402
import power_switch_decay as psd  # noqa: E402

MEASUREPREC = "set measureprec=12"
THREADS1 = "set num_threads=1"

#: The skeleton every power-tool request shares, in the order the committed JSON has it.
COMMON_KEYS = ("_comment", "netlist", "engine", "models", "corners", "analysis", "measurements")

#: tool -> the per-tool request content a shared builder must take as arguments and
#: reproduce exactly. ``remote``/``batch`` are None where the key must be ABSENT, which is
#: the half of this table a "just pass a dict" refactor loses first.
EXPECTED = {
    "power_switch": {
        "module": ps, "issue": 707, "slug": "power-switch request",
        "supply_param": "vsup", "n_units": 45, "analysis_args": "100p 3.5u",
        "remote": {"hosts": 3}, "batch": None, "timeout_s": 120,
        "ngspice_init": [MEASUREPREC, THREADS1],
    },
    "power_retention": {
        "module": pr, "issue": 790, "slug": "power-retention request",
        "supply_param": "vsup", "n_units": 45, "analysis_args": "1n 30u",
        "remote": {"hosts": 3}, "batch": {"capacity_wait_s": 600}, "timeout_s": 300,
        "ngspice_init": [MEASUREPREC, THREADS1],
    },
    "power_switch_decay": {
        "module": psd, "issue": 782, "slug": "power-switch decay request",
        "supply_param": "vsup", "n_units": 45, "analysis_args": "100 100000",
        "remote": {"hosts": 3}, "batch": None, "timeout_s": 120,
        "ngspice_init": [MEASUREPREC, THREADS1],
    },
    "liveness_sampler_power": {
        "module": lsp, "issue": 463, "slug": "liveness-sampler active-power request",
        "supply_param": "vsupply", "n_units": 27, "analysis_args": "5p 120n",
        "remote": None, "batch": None, "timeout_s": 7200,
        "ngspice_init": [MEASUREPREC],
    },
}

#: One point of the declared grid, present in all four grids.
PROBE = "tt/27/3.30"


class SharedSkeleton(unittest.TestCase):
    """What the four requests have in common, and must keep having."""

    def test_skeleton_fields_are_identical_across_the_four_tools(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                req = exp["module"].build_request()
                self.assertEqual(req["engine"], "ngspice")
                self.assertEqual(req["models"],
                                 {"pdk": "gf180mcuD", "lib": "libs.tech/ngspice/sm141064.ngspice"})
                self.assertEqual(req["analysis"]["kind"], "tran")
                self.assertTrue(req["options"]["keep_artifacts"])
                self.assertFalse(req["options"]["waveforms"])
                self.assertEqual(req["netlist"], exp["module"].DECK)

    def test_comment_names_the_issue_the_tool_and_the_unit_count(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                req = exp["module"].build_request()
                self.assertEqual(
                    req["_comment"],
                    f"issue #{exp['issue']} {exp['slug']}: {exp['n_units']} units. Generated by "
                    f"sim/tools/{name}.py; do not edit by hand "
                    "(`emit --check` fails if this drifts).")

    def test_declared_grid_is_the_product_of_the_three_axes(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                mod, req = exp["module"], exp["module"].build_request()
                corners = req["corners"]
                self.assertEqual(mod.n_units(), exp["n_units"])
                self.assertEqual(
                    len(corners["process"]) * len(corners["temperature_c"])
                    * len(corners["supply_v"][exp["supply_param"]]), exp["n_units"])
                for entry in corners["process"]:
                    self.assertEqual(sorted(entry), ["name", "sections"])
                    self.assertTrue(entry["sections"], f"{entry['name']} has no model sections")

    def test_top_level_key_order_matches_the_committed_json(self) -> None:
        """``remote``, then ``batch``, then ``options`` -- each only where it belongs.

        Key order is not cosmetic here: ``emit --check`` compares rendered JSON text.
        """
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                tail = [k for k, present in (("remote", exp["remote"]), ("batch", exp["batch"]))
                        if present is not None] + ["options"]
                self.assertEqual(list(exp["module"].build_request()), [*COMMON_KEYS, *tail])


class PerToolDifferences(unittest.TestCase):
    """The content a shared builder must take as arguments rather than unify."""

    def test_supply_parameter_name_is_per_tool(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                supply = exp["module"].build_request()["corners"]["supply_v"]
                self.assertEqual(list(supply), [exp["supply_param"]])
                self.assertEqual(supply[exp["supply_param"]], list(exp["module"].SUPPLIES_V))

    def test_analysis_args_keep_each_tools_own_unit_scaling(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                self.assertEqual(exp["module"].build_request()["analysis"]["args"],
                                 exp["analysis_args"])

    def test_remote_and_batch_blocks_are_present_only_where_declared(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                req = exp["module"].build_request()
                for key in ("remote", "batch"):
                    if exp[key] is None:
                        self.assertNotIn(key, req, f"{name} must not declare {key}")
                    else:
                        self.assertEqual(req[key], exp[key])

    def test_timeout_and_ngspice_init_are_per_tool(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                opts = exp["module"].build_request()["options"]
                self.assertEqual(opts["timeout_s"], exp["timeout_s"])
                self.assertEqual(opts["ngspice_init"], exp["ngspice_init"])

    def test_measurements_are_the_tools_own(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                self.assertEqual(exp["module"].build_request()["measurements"],
                                 exp["module"].measurements())


class SinglePointProbe(unittest.TestCase):
    """``--only``: the one thing allowed to run locally on a shared worker."""

    def test_probe_restricts_all_three_axes_and_nothing_else(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                full = exp["module"].build_request()
                req = exp["module"].build_request(PROBE)
                self.assertEqual([x["name"] for x in req["corners"]["process"]], ["tt"])
                self.assertEqual(req["corners"]["temperature_c"], [27])
                self.assertEqual(req["corners"]["supply_v"], {exp["supply_param"]: [3.3]})
                self.assertEqual(list(req), list(full))
                for key in [k for k in full if k not in ("_comment", "corners")]:
                    self.assertEqual(req[key], full[key], f"{key} changed for a probe")

    def test_probe_comment_says_one_unit_and_not_committed(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                self.assertEqual(
                    exp["module"].build_request(PROBE)["_comment"],
                    f"issue #{exp['issue']} single-point probe {PROBE}: 1 unit. "
                    "Generated; not committed.")

    def test_a_point_outside_the_declared_grid_is_rejected(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                with self.assertRaises(ValueError):
                    exp["module"].build_request("tt/27/3.00")


class CommittedRequestsAreCurrent(unittest.TestCase):
    def test_emit_check_passes_for_every_power_tool(self) -> None:
        for name, exp in EXPECTED.items():
            with self.subTest(tool=name):
                self.assertEqual(exp["module"].cmd_emit(check=True), 0)


if __name__ == "__main__":
    unittest.main()
