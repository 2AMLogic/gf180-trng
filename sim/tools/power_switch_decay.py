class DerivationError(ValueError):
    pass


def derive(v: dict, vdd: float) -> dict:
    out: dict = {"vdd_v": vdd}
    for k in CASES:
        t = tag(k)
        names = [f"{lab}_d{k}" for lab in LEVELS] + [f"vmin_d{k}", f"vfin_d{k}"]
        missing = [n for n in names if n not in v]
        if missing:
            raise DerivationError("readings missing: " + ", ".join(missing))
        for lab in LEVELS:
            raw = v[f"{lab}_d{k}"]
            reached = raw < CENSOR_S
            out[f"reached_{lab}_{t}"] = 1.0 if reached else 0.0
            out[f"t_decay_s_{lab}_{t}"] = raw - T_EDGE_S if reached else TSTOP_S - T_EDGE_S
        out[f"vmin_v_{t}"] = v[f"vmin_d{k}"]
        out[f"vfin_v_{t}"] = v[f"vfin_d{k}"]
    return out


def checks(row: dict) -> list[str]:
    bad = []
    vdd = row["vdd_v"]
    for k in CASES:
        t = tag(k)
        if not -0.05 < row[f"vmin_v_{t}"] < vdd:
            bad.append(f"vmin_v_{t} = {row[f'vmin_v_{t}']:.4g} V outside (-0.05, vdd)")
        for lab in LEVELS:
            if not row[f"t_decay_s_{lab}_{t}"] > 0:
                bad.append(f"t_decay_s_{lab}_{t} is not positive")
        # the minimum is the ground truth for "reached": it must agree with the crossing flag
        if (row[f"vmin_v_{t}"] <= OFF_FRACTION * vdd) != bool(row[f"reached_t05_{t}"]):
            bad.append(f"{t}: vmin and the 5 % crossing disagree")
        if row[f"reached_t50_{t}"] and row[f"reached_t90_{t}"] and \
                row[f"t_decay_s_t90_{t}"] > row[f"t_decay_s_t50_{t}"]:
            bad.append(f"{t}: 90 % level reached after the 50 % level")
    return bad


_vals = _pc.vals


def analyse_report(report: dict) -> list[dict]:
    return _pc.analyse_report(report, derive, checks, DerivationError)


def table(rows: list[dict]) -> str:
    t = tag(2)  # 200 pF, 10 ns
    head = f"{'corner':<14} {'t50 ms (200p/10n)':>18} {'t05 reached':>12} {'vmin mV':>9} verdict"
    lines = [head]
    for r in rows:
        if r["verdict"] == "UNMEASURED":
            lines.append(f"{r['corner']:<14} UNMEASURED: {'; '.join(r['problems'])}")
            continue
        lines.append(f"{r['corner']:<14} {r[f't_decay_s_t50_{t}'] * 1e3:>18.3f} "
                     f"{'yes' if r[f'reached_t05_{t}'] else 'no':>12} {r[f'vmin_v_{t}'] * 1e3:>9.1f} {r['verdict']}")
    return "\n".join(lines)


