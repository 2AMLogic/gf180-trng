REPO_ROOT = _ps.REPO_ROOT
TB_DIR = _ps.TB_DIR
DECK = "tb_power_switch_decay.sp"
REQUEST_NAME = "request-decay.json"
SLUG = "power-switch-decay"

PROCESSES, PROCESS_SECTIONS = _ps.PROCESSES, _ps.PROCESS_SECTIONS
TEMPS_C, SUPPLIES_V = _ps.TEMPS_C, _ps.SUPPLIES_V
#: Sleep rise starts here (the deck's PWL), so every time below is counted from it.
T_EDGE_S = 100e-9
TSTOP_S = 1e5
TSTEP_S = 100.0
#: A detector crossing at or after this means "not reached before TSTOP" (see module doc).
CENSOR_S = 0.995 * TSTOP_S  # below the deck's step at 0.999 * TSTOP by more than one print step
T_FINAL_S = 0.99 * TSTOP_S

#: case index -> (rail capacitance, sleep rise time); the same four cases as the wake group.
CASES = _ps.WAKE_CASES
#: detector label -> fraction of vdd the rail must fall to. 5 % mirrors the 95 % wake threshold.
LEVELS = {"t90": 0.90, "t50": 0.50, "t05": 0.05}
OFF_FRACTION = LEVELS["t05"]


def tag(k: int) -> str:
    return _ps.wake_tag(*CASES[k])


def measurements() -> list[dict]:
    m: list[dict] = []

    def add(name: str, spice: str, unit: str) -> None:
        m.append({"name": name, "spice": spice, "unit": unit})

    for k in CASES:
        for lab in LEVELS:
            add(f"{lab}_d{k}", f".meas tran {lab}_d{k} when v(c{lab}_{k})=0 fall=1", "s")
        add(f"vmin_d{k}", f".meas tran vmin_d{k} min v(vd{k}) from=0 to={TSTOP_S:g}", "V")
        add(f"vfin_d{k}", f".meas tran vfin_d{k} find v(vd{k}) at={T_FINAL_S:g}", "V")
    return m


def _build_full_request() -> dict:
    return {
        "_comment": (
            f"issue #782 power-switch decay request: {n_units()} units. Generated by "
            "sim/tools/power_switch_decay.py; do not edit by hand (`emit --check` fails if this drifts)."
        ),
        "netlist": DECK,
        "engine": "ngspice",
        "models": {"pdk": "gf180mcuD", "lib": "libs.tech/ngspice/sm141064.ngspice"},
        "corners": {
            "process": [{"name": p, "sections": PROCESS_SECTIONS[p]} for p in PROCESSES],
            "supply_v": {"vsup": list(SUPPLIES_V)},
            "temperature_c": list(TEMPS_C),
        },
        "analysis": {"kind": "tran", "args": f"{TSTEP_S:g} {TSTOP_S:g}"},
        "measurements": measurements(),
        "remote": {"hosts": _ps.HOSTS},
        "options": {
            "timeout_s": 120,
            "keep_artifacts": True,
            "waveforms": False,
            "ngspice_init": ["set measureprec=12", "set num_threads=1"],
        },
    }


def build_request(only: str | None = None) -> dict:
    req = _build_full_request()
    if only is None:
        return req
    proc, temp, vdd = _ps.parse_only(only)
    req["corners"]["process"] = [x for x in req["corners"]["process"] if x["name"] == proc]
    req["corners"]["temperature_c"] = [temp]
    req["corners"]["supply_v"] = {"vsup": [vdd]}
    req["_comment"] = f"issue #782 single-point probe {only}: 1 unit. Generated; not committed."
    return req


