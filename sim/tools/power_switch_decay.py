#!/usr/bin/env python3
"""Batch-fleet run, record ingestion and arithmetic for the gated-rail decay (issue #782).

    python3 sim/tools/power_switch_decay.py plan
    python3 sim/tools/power_switch_decay.py emit [--check]
    python3 sim/tools/power_switch_decay.py run --outdir DIR [--backend batch] [--only PROCESS/TEMP/VDD]
    python3 sim/tools/power_switch_decay.py record DIR/grid.report.json [--note TEXT]
    python3 sim/tools/power_switch_decay.py analyze DIR/grid.report.json [--json]
    python3 sim/tools/power_switch_decay.py summarize

Follow-up to ``power_switch.py`` (issue #707): same 400 um header, same leakage-equivalent load,
same rail capacitances (50 pF, 200 pF; assumptions) and the same two sleep edges, but the
switch starts on and OPENS, and the gated rail discharges. ``sim/tb/power-switch/
tb_power_switch_decay.sp`` says what is measured. The grid is the same 45 PVT points, submitted
to the batch fleet through ``klt sim`` and never swept locally on a shared worker; ``--only``
runs one point locally as a debug probe.

A ``.meas ... when`` that never crosses makes the whole unit an error, and "the rail never
reaches the threshold" is a result here, not a failure. So each detector carries a late step
that forces a crossing at 0.999 * TSTOP; a crossing time at or after ``CENSOR_S`` (0.995 * TSTOP) means
"not reached before TSTOP", and ``derive`` turns that into an explicit ``reached_*`` flag.
"""

