_label = _pc.label


def summary_text(recs: list[dict]) -> str:
    n = len(recs)
    lines = [f"Source: {n} records `sim/records/*-{SLUG}-NN.md` (current, status valid). Times are from the "
             "start of the sleep rise, in seconds; the run ends at "
             f"{TSTOP_S:g} s. A level is counted as reached only if the rail crossed it before then.", "",
             "| rail capacitance | sleep rise | corners reaching 50 % of vdd | corners reaching 5 % of vdd | "
             "slowest to 50 % among those (s, corner) | fastest to 50 % (s, corner) | "
             "highest final rail (V, corner) |", "|---|---|---|---|---|---|---|"]
    for k, (cap, trf) in CASES.items():
        t = tag(k)
        reach = sum(1 for r in recs if r["values"][f"reached_t05_{t}"] > 0.5)
        reach50 = [r for r in recs if r["values"][f"reached_t50_{t}"] > 0.5]
        slow = max(reach50, key=lambda r: r["values"][f"t_decay_s_t50_{t}"])
        fast = min(reach50, key=lambda r: r["values"][f"t_decay_s_t50_{t}"])
        hi = max(recs, key=lambda r: r["values"][f"vfin_v_{t}"])
        lines.append(
            f"| {cap * 1e12:g} pF | {trf * 1e9:g} ns | {len(reach50)} of {n} | {reach} of {n} | "
            f"{slow['values'][f't_decay_s_t50_{t}']:.4g} ({_label(slow)}) | "
            f"{fast['values'][f't_decay_s_t50_{t}']:.4g} ({_label(fast)}) | "
            f"{hi['values'][f'vfin_v_{t}']:.3f} ({_label(hi)}) |")
    t5 = [(r, tag(k)) for r in recs for k in CASES if r["values"][f"reached_t05_{tag(k)}"] > 0.5]
    if t5:
        worst, wt = max(t5, key=lambda x: x[0]["values"][f"t_decay_s_t05_{x[1]}"])
        lines += ["", f"Slowest decay to 5 % of vdd among the units that reach it: "
                  f"{worst['values'][f't_decay_s_t05_{wt}']:.4g} s ({_label(worst)}, case {wt})."]
    else:
        lines += ["", "No unit reaches 5 % of vdd."]
    return "\n".join(lines)


def cmd_summarize(records_dir: Path | None = None) -> int:
    recs = load_records(records_dir or REPO_ROOT / "sim" / "records")
    if not recs:
        print("no power-switch-decay measurement records", file=sys.stderr)
        return 2
    print(summary_text(recs))
    return 0


