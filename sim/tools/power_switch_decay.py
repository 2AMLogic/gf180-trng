        "testbench:", f"  path: {tb.relative_to(REPO_ROOT)}", f"  sha: {_report.blob_sha(REPO_ROOT, tb)}",
        "netlist:", f"  path: {netlist.relative_to(REPO_ROOT)}", f"  sha: {_report.blob_sha(REPO_ROOT, netlist)}",
