def document_problems(fam: dict[str, Rec], texts: dict[Path, str] | None = None) -> list[str]:
    """Every document-level check `--check` applies: the generated block is
    current, the prose around it agrees with that block, and no record family
    is named in prose.

    `texts` overrides what is read from disk, so the tests can perturb a
    document the same way they perturb `fam`.
    """
    missing = [n for n in PROSE_WORKLOADS if n not in workloads(fam)]
    if missing:
        return [f"{DOC.name}: prose states findings for workload(s) {missing}, which the records "
                "no longer contain -- re-read sections 0 and 4 instead of re-pinning them"]
    if BINDING not in fam:
        return [f"{DOC.name}: prose quotes the binding corner {BINDING}, absent from the family"]

    def text_of(path: Path) -> str | None:
        if texts is not None and path in texts:
            return texts[path]
        return path.read_text() if path.is_file() else None

    problems: list[str] = []
    doc_text = text_of(DOC)
    if doc_text is None:
        problems.append(f"{DOC.name} does not exist")
    elif BEGIN not in doc_text or END not in doc_text:
        problems.append(f"{DOC.name}: generated-table markers missing")
    else:
        body = doc_text.split(BEGIN, 1)[1].split(END, 1)[0].strip("\n")
        if body != markdown(fam):
            problems.append(f"{DOC.name}: generated tables are stale; run --markdown and paste "
                            "between the markers")
    try:
        pins_by_doc = prose_pins(fam)
    except CheckError as exc:
        return problems + [f"cannot re-derive the prose figures to check them against: {exc}"]
    for path, pins in pins_by_doc.items():
        text = text_of(path)
        if text is None:
            problems.append(f"{path.name} does not exist")
            continue
        if path == DOC and BEGIN in text and END in text:
            # Prose only: a figure standing inside the generated block must
            # not satisfy the sentence that restates it outside.
            text = text.split(BEGIN, 1)[0] + text.split(END, 1)[1]
        flat = _flat(text)
        for label, snippet in pins:
            if snippet not in flat:
                problems.append(f"{path.name}: {label} no longer quotes the generated figure -- "
                                f'the prose must read "{snippet}"')
    if doc_text is not None:
        for lit in sorted({m.group(0) for m in FAMILY_LITERAL.finditer(doc_text)}):
            problems.append(
                f"{DOC.name}: names the record family `{lit}-<nn>` in prose. Section 1 states the "
                "selection rule instead (the newest valid record per corner); a named family is "
                "stale at the next re-capture and nothing but this rule would catch it")
    return problems


def run_check(fam: dict[str, Rec]) -> int:
    problems = check(fam) + document_problems(fam)
    for p in problems:
        print(f"FAIL  {p}")
    if not problems:
        print(f"activity power characterization: {len(fam)} corners, {len(workloads(fam))} workloads x "
              f"{len(WINDOWS)} windows, trace identities consistent, uniform baseline equals the default "
              "flow, document block and prose figures current, no record family named in prose -- OK")
    return 1 if problems else 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--markdown", action="store_true")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)
    try:
        fam = load_family()
    except CheckError as exc:
        print(f"FAIL  {exc}")
        return 1
    if args.check:
        try:
            return run_check(fam)
        except CheckError as exc:
            print(f"FAIL  {exc}")
            return 1
    if args.markdown:
        print(markdown(fam))
    elif args.json:
        print(json.dumps({c: r.values for c, r in fam.items()}, indent=1))
    else:
        print(markdown(fam))
    return 0


