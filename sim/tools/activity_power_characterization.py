#!/usr/bin/env python3
"""Re-derive `sim/characterization-digital-activity-power.md` from its records
(#453) and gate the trace-dependent evidence behind it.

    python3 sim/tools/activity_power_characterization.py            # report
    python3 sim/tools/activity_power_characterization.py --markdown # the generated tables
    python3 sim/tools/activity_power_characterization.py --check    # gate (no PDK, no simulator)

The records are `sim/records/*-digital-sta-activity-<nn>.md` (one per corner
of the 15-point liberty x interconnect matrix, minted by
`run_sta.py --activity`). `--check` fails unless:

- a complete 15-corner family exists whose `netlist.sha` equals the committed
  `layout/digital/trng_top.def` blob and whose pinned `pnr.v` blob equals the
  committed `layout/digital/trng_top.pnr.v`;
- all 15 records pin the same trace identities (VCD and stimulus sha256,
  windows, seeds), and each stimulus hash equals what
  `activity_workloads.py` generates today (a changed workload makes the
  records stale, not silently wrong);
- each record pins the current gate-simulation testbench blob (strict:
  any edit to `activity_tb.v` stales the capture), and its committed raw
  `activity-manifest.json` (checksummed in the record) agrees with the
  record and, per workload, with what the capture program generates today:
  stimulus, cycle count, clock period, seeds and capture-window boundaries
  (semantic: the workloads module is not compared by blob, so a comment-only
  edit is harmless but a window-only change is not);
- the workload set equals the declared default campaign
  (`activity_workloads.WORKLOADS`) in every record, with missing, extra and
  duplicate workloads named. Diagnostic subset captures stay possible but
  are not accepted as the published aggregate;
- every record's uniform baseline equals the default flow's
  `digital-sta-power` 1 MHz total at the same corner and DEF (like-for-like
  by construction, re-verified);
- every (workload, window) in every record was annotated with no
  unannotated pins above the declared tolerance;
- the companion document contains exactly the tables this tool generates
  between its markers;
- the companion document's **prose** still quotes what this tool generates.
  Sections 0, 4 and 5 restate figures from the generated block in narrative
  form, and `characterization-digital-supply-ir-drop.md` restates this
  campaign's ratio bound once. Each pinned snippet is formatted from the
  records rather than written down here, so a re-capture that moves a number
  fails the document instead of silently outdating it (#883);
- the companion document names no `YYYY-MM-DD-digital-sta-activity` record
  family in prose. Section 1 states the selection rule this tool implements
  (newest valid record per corner) instead of pointing at a family that the
  next re-capture supersedes -- which is how the pointer and a dozen prose
  figures went stale for two re-captures while every check stayed green.

It never edits the ratified rollup baseline: the whole-block comparison it
prints is an illustrative substitution, labelled as such.
"""

