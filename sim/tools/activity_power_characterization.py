class CheckError(RuntimeError):
    pass


class Rec:
    def __init__(self, path: Path):
        text = path.read_text()
        self.path, self.stem = path, path.stem
        fm = re.match(r"---\n(.*?)\n---\n", text, re.S)
        if not fm:
            raise CheckError(f"{self.stem}: no frontmatter")
        self.fm = fm.group(1)
        self.status = self._one(r"^status:\s*(\S+)")
        self.liberty = self._one(r"^\s+liberty:\s*\S+__(\S+)")
        self.rc = self._one(r"^\s+interconnect:\s*(\S+)")
        self.vdd = float(self._one(r"^\s+voltage:\s*([\d.]+)"))
        self.def_sha = self._one(r"^netlist:\s*\n\s+path:.*\n\s+sha:\s*([0-9a-f]+)")
        self.pnr_sha = self._one(r"netlist layout/digital/trng_top\.pnr\.v \(sha ([0-9a-f]+)\)")
        self.traces = re.findall(
            r"- workload: (\S+)\n\s+vcd_sha256: (\w+)\n\s+vcd_bytes: (\d+)\n\s+stimulus_sha256: (\w+)\n"
            r"\s+cycles: (\d+)\n\s+windows_cycles: (\{.*\})\n", self.fm)
        self.testbench_sha = self._one(r"^\s+testbench_sha:\s*([0-9a-f]{40})\s*$")
        self.raw_path = self._one(r"^raw:\s*\n\s+path:\s*(\S+)")
        self.manifest_sha = self._one(r"^\s+- activity-manifest\.json\s+sha256:([0-9a-f]{64})")
        self._manifest = None
        self.seeds = self._one(r"^seeds:\s*(.*)$")
        self.values = parse_result_values(text, label=self.stem, error_cls=CheckError)
        self.corner = f"{self.liberty}/rc-{self.rc}"

    def _one(self, pat: str) -> str:
        m = re.search(pat, self.fm, re.M)
        if not m:
            raise CheckError(f"{self.stem}: cannot find /{pat}/ in the frontmatter")
        return m.group(1)

    def manifest(self) -> dict:
        """The committed raw activity manifest, checksummed against the record."""
        if self._manifest is None:
            path = REPO_ROOT / self.raw_path / "activity-manifest.json"
            if not path.is_file():
                raise CheckError(f"{self.stem}: raw manifest {path.relative_to(REPO_ROOT)} is missing")
            if hashlib.sha256(path.read_bytes()).hexdigest() != self.manifest_sha:
                raise CheckError(f"{self.stem}: raw manifest does not match its recorded sha256")
            self._manifest = json.loads(path.read_text())
        return self._manifest

    def v(self, key: str) -> float:
        if key not in self.values:
            raise CheckError(f"{self.stem}: no `{key}`")
        return self.values[key]


def load_family() -> dict[str, Rec]:
    recs = current_records(
        RECORDS, "*-digital-sta-activity-[0-9]*.md", make=Rec, error_cls=CheckError)
    cur_def = blob_sha(REPO_ROOT / "layout/digital/trng_top.def")
    cur_pnr = blob_sha(REPO_ROOT / "layout/digital/trng_top.pnr.v")
    fam: dict[str, Rec] = {}
    stale = []
    for r in recs:
        if r.def_sha != cur_def or r.pnr_sha != cur_pnr:
            stale.append(r.stem)
            continue
        fam[r.corner] = r  # sorted by stem: the latest valid record wins
    missing = [c for c in EXPECTED if c not in fam]
    if missing:
        raise CheckError(
            f"no complete current-netlist family: missing {missing}"
            + (f"; {len(stale)} record(s) describe an earlier DEF/netlist" if stale else "")
        )
    return fam


def workloads(fam: dict[str, Rec]) -> list[str]:
    names = sorted({t[0] for r in fam.values() for t in r.traces})
    return names


def key(workload: str, window: str, term: str) -> str:
    return f"obs_{workload.replace('-', '_')}_{window}_{term}"


def campaign_problems(r: Rec, expected: tuple[str, ...]) -> list[str]:
    """Missing / extra / duplicate workloads in one record's trace list."""
    names = [t[0] for t in r.traces]
    out = [f"{r.stem}: duplicate workload trace {n}" for n in sorted({n for n in names if names.count(n) > 1})]
    missing = [n for n in expected if n not in names]
    extra = sorted(set(names) - set(expected))
    if missing:
        out.append(f"{r.stem}: incomplete campaign, missing workload(s) {missing}")
    if extra:
        out.append(f"{r.stem}: undeclared workload(s) {extra} not in the default campaign")
    return out


def capture_source_problems(r: Rec) -> list[str]:
    """Freshness of the capture program behind one record (no VCD/PDK needed)."""
    import activity as act  # noqa: PLC0415

    out: list[str] = []
    cur_tb = blob_sha(act.TB_SOURCE)
    if r.testbench_sha != cur_tb:
        out.append(f"{r.stem}: stale capture testbench: record pins {r.testbench_sha}, "
                   f"{act.TB_SOURCE.name} is now {cur_tb}")
    try:
        m = r.manifest()
        act.verify_capture_source(m, f"{r.stem} raw manifest")
    except (CheckError, act.ActivityError, KeyError, ValueError) as exc:
        return out + [str(exc)]
    if m["identities"]["testbench"]["git_blob_sha"] != r.testbench_sha:
        out.append(f"{r.stem}: record testbench_sha differs from its raw manifest")
    by_name = {}
    for n, t in m["traces"].items():
        by_name[n] = t
    if sorted(by_name) != sorted(t[0] for t in r.traces):
        out.append(f"{r.stem}: record traces {sorted(t[0] for t in r.traces)} differ from raw manifest "
                   f"traces {sorted(by_name)}")
    for name, vcd, size, stim, cycles, win in r.traces:
        t = by_name.get(name)
        if t is None:
            continue
        try:
            same = (t["vcd_sha256"] == vcd and str(t["vcd_bytes"]) == size
                    and t["stimulus_sha256"] == stim and str(t["cycles"]) == cycles
                    and json.loads(win) == t["windows_cycles"])
        except (KeyError, ValueError):
            same = False
        if not same:
            out.append(f"{r.stem}: trace {name} in the record differs from its raw manifest")
    return out


def check(fam: dict[str, Rec], expected: tuple[str, ...] | None = None) -> list[str]:
    problems: list[str] = []
    import activity_workloads as wl  # noqa: PLC0415

    expected = tuple(wl.WORKLOADS) if expected is None else expected
    for r in fam.values():
        problems += campaign_problems(r, expected)
        problems += capture_source_problems(r)

    first = next(iter(fam.values()))
    for c, r in fam.items():
        if r.traces != first.traces or r.seeds != first.seeds:
            problems.append(f"{r.stem}: trace identities differ from {first.stem}")
    if not first.traces:
        problems.append("records pin no traces")
    for name, _vcd, _bytes, stim, cycles, _win in first.traces:
        if name not in wl.WORKLOADS:
            problems.append(f"workload {name} no longer exists")
            continue
        rows, _ = wl.build(name)
        if wl.stimulus_sha256(rows) != stim or len(rows) != int(cycles):
            problems.append(f"workload {name}: records are stale (stimulus changed)")
    # Like-for-like re-verification against the default flow's records, read
    # through that family's one reader: it applies the record lifecycle, binds
    # every record to the committed routed DEF -- the same DEF `load_family`
    # has already pinned these activity records to -- and raises naming the
    # missing corners rather than quietly comparing against a short family.
    try:
        default = {r.corner: r.values for r in dcc.load()}
    except dcc.RecordError as exc:
        default = {}
        problems.append(f"no default-flow family to compare against: {exc}")
    for c, r in fam.items():
        base = default.get(c)
        if base is None:
            # `dcc.load` either yields the whole grid or raises (reported once
            # above), so this only fires for a corner outside that grid.
            if default:
                problems.append(f"{c}: no default-flow record for the same DEF to compare against")
            continue
        a, b = r.v("uniform_total_w"), base["p_total_1mhz_w"]
        if abs(a - b) > 1e-6 * b:
            problems.append(f"{c}: uniform baseline {a:.6e} != default flow {b:.6e}")
    for c, r in fam.items():
        for name in [n for n in workloads(fam) if n in expected]:
            for w in WINDOWS:
                ann = r.v(key(name, w, "annotated_pins"))
                un = r.v(key(name, w, "unannotated_pins"))
                if ann <= 0 or un / (ann + un) > MAX_UNANNOTATED_FRACTION:
                    problems.append(f"{c} {name}/{w}: {int(un)} of {int(ann + un)} pins unannotated")
                parts = sum(r.v(key(name, w, t)) for t in ("internal_w", "switching_w", "leakage_w"))
                if abs(parts - r.v(key(name, w, "total_w"))) > 1e-5 * parts:
                    problems.append(f"{c} {name}/{w}: terms do not sum to the total")
    return problems


