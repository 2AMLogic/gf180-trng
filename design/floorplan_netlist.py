_SUBCKT_HEADER_RE = re.compile(r"^\.subckt\s+(\S+)\s+(.*)$", re.MULTILINE | re.IGNORECASE)


def _join_spice_continuations(text: str) -> str:
    """Fold every SPICE `+`-prefixed continuation line into its predecessor
    -- the same small helper `layout/floorplan/floorplan.py`'s own
    `_reference_top_pins` and `layout/digital/lvs.py`'s own `_library_cell_
    pins` each keep a private copy of, for the same reason: it only ever
    reads a header a reference file already carries, never builds one.
    """
    joined: list[str] = []
    for line in text.split("\n"):
        if line.startswith("+") and joined:
            joined[-1] = f"{joined[-1]} {line[1:].strip()}"
        else:
            joined.append(line)
    return "\n".join(joined)


def reference_top_pins(path: Path, top: str) -> list[str]:
    """The declared pin list off `path`'s own `.SUBCKT <top> ...` header."""
    if not path.is_file():
        raise FloorplanNetlistError(
            f"{path.relative_to(REPO_ROOT)} does not exist -- cannot read its "
            f"`.SUBCKT {top}` pin list"
        )
    text = _join_spice_continuations(path.read_text(errors="replace"))
    for name, pins in _SUBCKT_HEADER_RE.findall(text):
        if name.lower() == top.lower():
            return pins.split()
    raise FloorplanNetlistError(
        f"{path.relative_to(REPO_ROOT)} has no `.SUBCKT {top}` header -- "
        "cannot derive its declared pin list"
    )


# --------------------------------------------------------------------------- #
# Self-check -- issue #221's own acceptance criterion: verify every declared
# endpoint against the real, committed reference files, mechanically.
# --------------------------------------------------------------------------- #


def validate_inter_region_nets() -> list[str]:
    """Return a list of human-readable problems; empty means the declared
    net list is internally consistent with the four regions' own committed
    reference `.spice` files. Needs no `klt`, no PDK -- everything here is a
    plain-text read of files already committed to this repository.
    """
    problems: list[str] = []

    pins_by_region: dict[str, list[str]] = {}
    for rid, (path, top) in REGION_REFERENCES.items():
        try:
            pins_by_region[rid] = reference_top_pins(path, top)
        except FloorplanNetlistError as exc:
            problems.append(str(exc))
            pins_by_region[rid] = []

    seen_names: set[str] = set()
    claimed_pins: dict[tuple[str, str], str] = {}  # (region, pin) -> net name

    for net in INTER_REGION_NETS:
        name = net["name"]
        if name in seen_names:
            problems.append(f"net {name!r} is declared more than once")
        seen_names.add(name)

        for rid, pin in net.get("endpoints", ()):
            if rid not in REGION_REFERENCES:
                problems.append(
                    f"net {name!r} names unknown region {rid!r} (not in "
                    "REGION_REFERENCES)"
                )
                continue
            if pin not in pins_by_region[rid]:
                problems.append(
                    f"net {name!r} claims region {rid!r} pin {pin!r}, but "
                    f"{REGION_REFERENCES[rid][0].relative_to(REPO_ROOT)}'s own "
                    f"`.SUBCKT {REGION_REFERENCES[rid][1]}` header does not "
                    f"declare that pin (has: {pins_by_region[rid]})"
                )
                continue
            prior = claimed_pins.get((rid, pin))
            if prior is not None and prior != name:
                problems.append(
                    f"region {rid!r} pin {pin!r} is claimed by two different "
                    f"nets ({prior!r} and {name!r})"
                )
            claimed_pins[(rid, pin)] = name

        for rid, specialnet in net.get("implicit_regions", ()):
            if rid != "digital":
                problems.append(
                    f"net {name!r} declares an `implicit_regions` entry for "
                    f"region {rid!r} -- only 'digital' has undeclared "
                    "SPECIALNETS-only supply pins (see DIGITAL_IMPLICIT_"
                    "SPECIALNETS's own docstring)"
                )
            if specialnet not in DIGITAL_IMPLICIT_SPECIALNETS:
                problems.append(
                    f"net {name!r} declares an `implicit_regions` entry "
                    f"naming {specialnet!r}, which is not one of "
                    f"DIGITAL_IMPLICIT_SPECIALNETS {DIGITAL_IMPLICIT_SPECIALNETS}"
                )
            if specialnet != name:
                problems.append(
                    f"net {name!r}'s own `implicit_regions` entry names "
                    f"specialnet {specialnet!r}, which does not match this "
                    "net's own name -- an implicit connection should always "
                    "be declared under the net it is a connection *of*"
                )

        for rid in net.get("spans_regions", ()):
            if rid not in REGION_REFERENCES:
                problems.append(
                    f"net {name!r}'s `spans_regions` names unknown region "
                    f"{rid!r}"
                )

    # -- Every ring1/ring2/combiner_sampler pin must be claimed by exactly
    # one net: these three regions' own `.SUBCKT` headers are short and
    # fully analog/inter-region by construction (see the module docstring),
    # so an unclaimed pin here means either this table or that region's own
    # committed reference has drifted and nobody has reconciled them yet.
    for rid in ("ring1", "ring2", "combiner_sampler"):
        unclaimed = [
            pin for pin in pins_by_region.get(rid, ()) if (rid, pin) not in claimed_pins
        ]
        if unclaimed:
            problems.append(
                f"region {rid!r}'s own committed reference declares "
                f"pin(s) {unclaimed} that no INTER_REGION_NETS entry claims"
            )

    # -- The star-point separation invariant (module docstring): vddr1,
    # vddr2, vdd, vddd must be four distinct nets with disjoint endpoint
    # regions, so a future edit cannot silently merge two of them.
    supply_nets = [net for net in INTER_REGION_NETS if net["role"] == "supply"]
    supply_names = [net["name"] for net in supply_nets]
    if sorted(supply_names) != ["vdd", "vddd", "vddr1", "vddr2"]:
        problems.append(
            "expected exactly the four supply nets {vdd, vddd, vddr1, "
            f"vddr2}}, found {sorted(supply_names)}"
        )
    supply_regions: dict[str, str] = {}
    for net in supply_nets:
        regions = {rid for rid, _ in net.get("endpoints", ())}
        regions |= {rid for rid, _ in net.get("implicit_regions", ())}
        for rid in regions:
            prior = supply_regions.get(rid)
            if prior is not None and prior != net["name"]:
                problems.append(
                    f"region {rid!r} is reached by two different supply "
                    f"nets ({prior!r} and {net['name']!r}) -- the four "
                    "supply branches must stay separate to their own star "
                    "point"
                )
            supply_regions[rid] = net["name"]

    # -- ro1's long-haul flag (module docstring / issue #221 acceptance
    # criterion) must survive.
    ro1 = next((net for net in INTER_REGION_NETS if net["name"] == "ro1"), None)
    if ro1 is None:
        problems.append("net 'ro1' (ring1.ro -> combiner_sampler.rn1) is missing")
    elif ro1.get("spans_regions") != ["ring2"]:
        problems.append(
            "net 'ro1' must declare spans_regions == ['ring2'] (the long-"
            f"haul route around ring2's own guarded region); found "
            f"{ro1.get('spans_regions')!r}"
        )

    return problems


# --------------------------------------------------------------------------- #
# The LVS-reference generator
# --------------------------------------------------------------------------- #


def _endpoint_map() -> dict[tuple[str, str], str]:
    """`(region_id, region_pin_name) -> composed top-level net name`, for
    every declared, mechanically-checkable endpoint."""
    mapping: dict[tuple[str, str], str] = {}
    for net in INTER_REGION_NETS:
        for rid, pin in net.get("endpoints", ()):
            mapping[(rid, pin)] = net["name"]
    return mapping


def _wired_pins(rid: str, mapping: dict[tuple[str, str], str]) -> list[str]:
    """The net name wired to each of `rid`'s own pins, in that region's own
    committed pin order -- an unmapped pin passes through under its own
    name (only `digital` has any: its 105 chip-only pins)."""
    path, top = REGION_REFERENCES[rid]
    return [mapping.get((rid, pin), pin) for pin in reference_top_pins(path, top)]


def _external_pins() -> list[str]:
    """Every `trng_floorplan`-level chip pin: each `chip_pin: True` net's
    own name, plus every region pin that passes through unmapped (`digital`
    only). Sorted the same plain-string way `layout/digital/lvs.py`'s own
    `_top_pins` sorts `trng_top`'s header, so the two headers agree on
    convention even though this one is smaller.
    """
    mapping = _endpoint_map()
    external: set[str] = {net["name"] for net in INTER_REGION_NETS if net["chip_pin"]}
    mapped_pins = set(mapping)
    for rid in REGION_REFERENCES:
        path, top = REGION_REFERENCES[rid]
        for pin in reference_top_pins(path, top):
            if (rid, pin) not in mapped_pins:
                external.add(pin)
    return sorted(external)


def generate_lvs_reference() -> str:
    """Build `trng_floorplan.lvs_reference.spice`'s own text (does not write
    it -- see `write_lvs_reference`). Raises `FloorplanNetlistError` if
    `validate_inter_region_nets()` finds a problem; a composed reference
    built over a broken declaration would just be a second, differently-
    broken artefact.
    """
    problems = validate_inter_region_nets()
    if problems:
        raise FloorplanNetlistError(
            "cannot generate the composed LVS reference: "
            + "; ".join(problems)
        )

    mapping = _endpoint_map()
    external_pins = _external_pins()

    lines = [
        "* trng_floorplan -- LVS reference (composed) netlist.",
        "*",
        "* Generated by design/floorplan_netlist.py -- do not hand-edit.",
        "* Phase 1 of issue #219's own two-phase decomposition (issue #221):",
        "* this file wires the four regions' own already-committed reference",
        "* subcircuits together per INTER_REGION_NETS, declared as reviewable",
        "* Python data in that module. It does NOT correspond to any drawn",
        "* geometry yet -- the physical routing, the klt extract --top",
        "* trng_floorplan pin-count change, and running klt lvs against this",
        "* file are phase 2's work (a separate, follow-up issue), not done here.",
        "*",
        "* vddd is written as a top-level pin below with no wire beneath it:",
        "* digital's own committed reference (layout/digital/trng_top.lvs_",
        "* reference.spice) does not declare a vddd .SUBCKT pin (SPECIALNETS-",
        "* only -- see design/floorplan_netlist.py's own module docstring).",
        "* vss is wired to ring1/ring2/combiner_sampler only for the same",
        "* reason; digital's own vss return is real but not expressible here.",
        "*",
        "* Each region's own reference is pulled in by .INCLUDE rather than",
        "* copied a second time (digital's own reference alone is ~8700",
        "* lines) -- paths below are relative to this file's own directory.",
    ]

    for rid in REGION_ORDER:
        path, _top = REGION_REFERENCES[rid]
        rel = os.path.relpath(path, LVS_REFERENCE_PATH.parent)
        lines.append(f".INCLUDE {rel}")
    lines.append("")

    lines.append(f".SUBCKT {TOP_CELL} " + " ".join(external_pins))
    for rid in REGION_ORDER:
        _path, top = REGION_REFERENCES[rid]
        nets = _wired_pins(rid, mapping)
        lines.append(f"X_{rid.upper()} " + " ".join(nets) + f" {top}")
    lines.append(f".ENDS {TOP_CELL}")
    lines.append("")

    return "\n".join(lines) + "\n"


def write_lvs_reference() -> Path:
    text = generate_lvs_reference()
    LVS_REFERENCE_PATH.write_text(text)
    return LVS_REFERENCE_PATH


# --------------------------------------------------------------------------- #
# CLI
# --------------------------------------------------------------------------- #


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="floorplan_netlist.py",
        description=(
            "Declare the trng_floorplan inter-region net list and self-"
            "check it against the four regions' own committed reference "
            "netlists (issue #221)."
        ),
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help="also (re)write layout/floorplan/trng_floorplan.lvs_reference.spice",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="self-check only (the default with no flags)",
    )
    args = parser.parse_args(argv)

    problems = validate_inter_region_nets()
    print(f"inter-region nets declared: {len(INTER_REGION_NETS)}")
    if problems:
        print(f"FAIL: {len(problems)} problem(s):")
        for problem in problems:
            print(f"  - {problem}")
        return EXIT_FAIL
    print("PASS: every declared endpoint names a real pin on its region's "
          "own committed reference netlist.")

    if args.write:
        path = write_lvs_reference()
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    elif not args.check:
        # No flags at all: still report whether the committed file matches
        # what this declaration would generate, without writing anything.
        generated = generate_lvs_reference()
        if not LVS_REFERENCE_PATH.is_file():
            print(
                f"NOTE: {LVS_REFERENCE_PATH.relative_to(REPO_ROOT)} does not "
                "exist yet -- re-run with --write to create it"
            )
        elif LVS_REFERENCE_PATH.read_text() != generated:
            print(
                f"NOTE: {LVS_REFERENCE_PATH.relative_to(REPO_ROOT)} does not "
                "match this declaration -- re-run with --write to refresh it"
            )
        else:
            print(f"ok    {LVS_REFERENCE_PATH.relative_to(REPO_ROOT)} matches "
                  "this declaration")

    return EXIT_OK


if __name__ == "__main__":
    raise SystemExit(main())
