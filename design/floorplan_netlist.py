#!/usr/bin/env python3
"""Declare the `trng_floorplan` inter-region net list, and generate its
top-level LVS reference netlist from that declaration.

    python3 design/floorplan_netlist.py            # self-check, print summary
    python3 design/floorplan_netlist.py --check     # self-check only (same as no args)
    python3 design/floorplan_netlist.py --write     # ... and (re)write the LVS reference

This is **phase 1** of issue #219's two-phase decomposition: a
Python-checkable *data and rationale* declaration, not yet drawn geometry.
`layout/floorplan/floorplan.py`'s `compose()` places four guarded regions
(`ring1`, `ring2`, `combiner_sampler`, `digital`) into one abstract with an
isolation channel between neighbours, but draws no wiring between them --
every net that has to cross a region boundary for the block to actually
function is undeclared today. This module is where that gets written down,
once, as reviewable data: the input contract phase 2 (a separate follow-up
issue, physical routing + DRC/LVS) routes against, so the two phases can
never independently drift on what the net list is.

**No GDS/DRC/LVS work happens here.** `klt extract --top trng_floorplan`'s
pin count is unaffected by this module alone -- nothing it does touches the
composed GDS. See `layout/floorplan/README.md`, "Planned inter-region
connectivity", for the write-up this module's own data backs.

Why a new module, not `design/netlist.py`
-------------------------------------------
`design/netlist.py` is exclusively an xschem-schematic-to-SPICE exporter
(`design/xschem/*.sch` -> `design/*.spice`; see its own module docstring and
`TOP_CELLS`). There is no `design/xschem/trng_floorplan.sch` -- the
floorplan's own inter-region netlist is not a schematic export, it is a
*layout-composition-level* declaration, the same kind of thing
`layout/digital/lvs.py` builds for `trng_top.lvs_reference.spice` (a
hand-derived, `.SUBCKT`-wrapped reference netlist generated by a Python
script under `layout/`, not xschem). This module follows that pattern one
level up: one composed reference for all four regions together, generated
from data declared here and consumed by `layout/floorplan/floorplan.py`
(which imports this module rather than restating any of it).

What is declared, per net (`INTER_REGION_NETS`)
--------------------------------------------------
- `name` -- the net's own name at the composed `trng_floorplan` level.
- `role` -- one of `control` / `clock` / `reset` / `entropy_tap` /
  `raw_tap` / `liveness_tap` / `supply` / `ground` / `substrate`.
- `chip_pin` -- whether this net is also a top-level `trng_floorplan` pin
  (an actual chip I/O), as opposed to a net that is wholly absorbed between
  two regions and never reaches the outside world.
- `endpoints` -- every `(region_id, region_pin_name)` this net connects,
  using **each region's own already-committed reference pin name**
  (`REGION_REFERENCES`) -- never a name invented here. `validate_inter_
  region_nets()` mechanically checks every one of these against the real
  `.SUBCKT` header of the region's own committed `.spice` file, so a typo or
  a region's own future pin rename is caught, not eyeballed.
- `implicit_regions` -- for the two nets (`vddd`, `vss`) that also reach
  `digital`'s real power delivery network through a mechanism `digital`'s
  own committed reference does not expose as a `.SUBCKT` pin at all (see
  "The `digital` region's supply pins are not `.SUBCKT` pins" below). Not
  mechanically checkable the same way `endpoints` is -- there is no pin to
  check against -- so it is kept in its own field rather than silently
  folded into `endpoints`, where it would look checkable and would not be.
- `spans_regions` -- for `ro1` only: the one net whose physical routing path
  (phase 2's job) is not a single-channel hop between adjacent regions.
- `layer_role` -- a target metal-layer *role* (not yet a GDS layer number),
  tied to which coupling mechanism (`layout/floorplan/README.md`'s
  Mechanism 1/2/3) the route must not defeat.
- `rationale` -- why the net exists and why its endpoints/layer choice are
  what they are, tied to the README.

The four supply branches must never merge before a star point
-----------------------------------------------------------------
**`vddr1`, `vddr2`, `vdd` and `vddd` are four topologically distinct nets,
declared as four separate dict entries below with four separate `name`
fields and four disjoint `endpoints` lists. Do not merge them, ever, no
matter how tempting a shared strap looks during phase 2's routing pass.**
`layout/floorplan/README.md`'s Mechanism 1 (per-ring supply routing, item 2)
and Mechanism 2 (star routing, item 1) both depend on these four branches
carrying no shared series impedance until a not-yet-drawn star point at the
block's own supply pad. `validate_inter_region_nets()` asserts this
mechanically (four distinct names, no two supply nets sharing an endpoint or
a region) so a future edit cannot merge them without this check failing.

The `digital` region's supply pins are not `.SUBCKT` pins
--------------------------------------------------------------
`layout/digital/trng_top.lvs_reference.spice`'s own `.SUBCKT trng_top`
header declares 109 pins (verified directly, at run time, by `reference_
top_pins()` below -- not restated as a constant here; #219's own "~12-pin"
note is a caution about trusting a stale figure instead of re-deriving it,
and this module follows that caution rather than repeating it) -- none of
them `vddd` or `vss`. That is deliberate, not an oversight:
`layout/digital/lvs.py`'s own module docstring ("Neither side promotes a
supply to a *top-level* pin", "`run_extract`'s `--pins` declares the 109
real chip I/O nets and nothing else") and `layout/digital/README.md#power`
both record that `digital`'s real, placed-and-routed power delivery network
is real (its `SPECIALNETS` section names `vddd`/`vss`, and the *DEF's own*
`PINS` section -- the physical layout, not this reference netlist's
`.SUBCKT` header -- carries 111 entries, the same 109 chip I/O plus those 2
supply pins), but the *reference netlist* that standalone digital LVS run
built keeps `vddd`/`vss` off both sides' `.SUBCKT trng_top` interface so the
two interfaces still match each other. This module's own `INTER_REGION_NETS`
declares `vddd`'s and `vss`'s connection into `digital` via `implicit_
regions` rather than `endpoints` for exactly that reason: there is no
`.SUBCKT` pin to name. `generate_lvs_reference()` below therefore cannot
wire either net into `digital`'s own `X`-card (the card only has as many
positions as the reference's own header declares) -- `vddd` is written as a
top-level `trng_floorplan` pin with no real wire beneath it in this
generated file, and `vss` is written wired to `ring1`/`ring2`/
`combiner_sampler` only. Both are flagged in the generated file's own header
comment. Reconciling this (if phase 2 needs to) is that follow-up issue's
problem, not this declaration's.

The substrate net `vsubs` (not in issue #219/#221's own inter-region table)
--------------------------------------------------------------------------------
`ring1`, `ring2` and `combiner_sampler`'s own committed reference netlists
each declare a `vsubs` pin (`layout/rings/ro_ring11/ro_ring11.spice`'s own
header comment: "NMOS bulk is the deck's `vsubs` substrate global" --
`layout/verify.py`'s own `EXPECTATIONS` table explains the same thing from
the extraction side: `klt extract` *synthesizes* this net rather than
resolving it from a real drawn label, which is exactly why `device.body_
unverified` is an expected, not a real, LVS disclosure on every one of those
three regions' own standalone checks). `design/trng_top.spice`'s schematic
has no `vsubs` pin at all -- it is a layout-LVS-reference artifact of the
three `klt gen`/`klt draw`-descended regions' own hand-derived `.spice`
files, not part of the design's own inter-region signal/supply list the
issue's table enumerates. It is declared here anyway, as its own net (not
merged into `vss`, even though the guard rings' own p-substrate taps are
physically tied to each region's `vss` return per README Mechanism 2 -- that
is a DRC/physical statement about drawn geometry, not a schematic-netlist
statement, and this reference stays a textually distinct node the same way
the extraction deck's own synthesized `vsubs` handle stays distinct from a
real `vss` label), purely so `generate_lvs_reference()` below can wire a
complete, well-formed `X`-card for all three regions (their own `.SUBCKT`
headers require a 5th/11th pin no matter what this module declares). `digital`
has no `vsubs` pin (its standard-cell library ties NMOS bulk internally, the
same way it has no separate pin for it in any of its abstracted cell types --
see `layout/digital/trng_top.lvs_reference.spice`'s own per-cell-type
`.SUBCKT` headers, none of which carry one either), so `vsubs` never reaches
`digital` and is not a `trng_floorplan` chip pin.

The `ro1` long-haul route (`spans_regions`)
------------------------------------------------
`ring1.ro -> combiner_sampler.rn1` is the one net in this table whose
physical route (phase 2's job) is not a single-channel hop: the composed row
order is `ring1 | ring2 | combiner_sampler | digital`, so this net's two
endpoints are not adjacent regions -- it has to cross, or route around in
the channel space, `ring2`'s own guarded region. `spans_regions: ["ring2"]`
records that so phase 2 does not have to re-discover it by reading the row
order itself.

The `.lvs_reference.spice` generator
----------------------------------------
`generate_lvs_reference()` writes a hand-derived, `.SUBCKT`-wrapped
composed reference at `layout/floorplan/trng_floorplan.lvs_reference.spice`,
the same documented style `layout/floorplan/floorplan.py`'s own
`RING_LVS_REFERENCE` entries and `layout/digital/lvs.py`'s own
`trng_top.lvs_reference.spice` generation already use. Rather than inlining
each region's own (in `digital`'s case, ~8700-line) reference content a
second time -- which would create exactly the two-copies-that-can-drift
problem this repository otherwise goes out of its way to avoid -- it
`.INCLUDE`s the four already-committed reference files by their own
repo-relative path and instantiates each one's own `.SUBCKT` once. **This
file's own well-formedness (does it parse, does it `klt lvs`-match anything)
is not verified here** -- running `klt lvs` against it is phase 2's job, once
real routed geometry exists to compare it against. What this module verifies
is narrower and immediate: that every endpoint it wires actually names a
real pin on the region it claims to (`validate_inter_region_nets()`).
"""

